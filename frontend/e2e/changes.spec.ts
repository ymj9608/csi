import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';

const env = Object.fromEntries(readFileSync('../.env', 'utf8').split('\n').filter(s => s.includes('=')).map(s => [s.slice(0, s.indexOf('=')), s.slice(s.indexOf('=') + 1)]));
const addedScan = process.env.CSI_CHANGE_ADDED_SCAN;
const fixedScan = process.env.CSI_CHANGE_FIXED_SCAN;

test('real commit diff, linked AI review, removed candidates, legacy state and mobile', async ({ page }) => {
  test.skip(!addedScan || !fixedScan, 'Provide two completed LOCAL_DEMO scan IDs; see docs/CHANGE_REVIEWS.md');
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('/login');
  await page.getByLabel('계정', { exact: true }).fill(env.CSI_ADMIN_USERNAME);
  await page.getByLabel('비밀번호', { exact: true }).fill(env.CSI_ADMIN_PASSWORD);
  await page.getByRole('button', { name: '로그인', exact: true }).click();
  await expect(page.getByRole('heading', { name: '보안 현황' })).toBeVisible();
  const changesResponse = await page.request.get(`/api/scans/${addedScan}/changes`);
  expect(changesResponse.ok()).toBeTruthy();
  const changes = await changesResponse.json();
  expect(changes.status).toBe('AVAILABLE');
  expect(changes.review.summaryMode).toBe('STATIC_FACTS');
  const model = changes.files.find((f: any) => f.facts.some((x: any) => x.symbol === 'CsiSignupProfile.phone_number' && x.kind === 'FIELD_ADDED'));
  expect(model).toBeTruthy();
  await page.goto(`/scans/${addedScan}`);
  const section = page.getByRole('region', { name: '코드 변경 리뷰' });
  await expect(section).toBeVisible();
  await page.getByLabel('변경 파일', { exact: true }).selectOption(model.changeId);
  await expect(section).toContainText(changes.baseSha);
  await expect(section).toContainText(changes.headSha);
  await expect(section).toContainText('실습 프로필 전화번호 모델 · 필드 선언 추가');
  await expect(section.locator('.source-diff tbody tr')).toHaveCount(model.rows.length);
  await expect(section.locator('.diff-after').filter({ hasText: 'phone_number' }).first()).toBeVisible();
  await expect(section.locator('.change-risk').first()).toContainText('정적 후보');
  const findings = await (await page.request.get(`/api/scans/${addedScan}/findings`)).json();
  const linked = findings.filter((f: any) => f.filePath === model.filePath);
  expect(linked.length).toBeGreaterThan(0);
  expect(linked.every((f: any) => f.analysis.changeContext && f.analysis.citedFactIds.includes('C1'))).toBeTruthy();
  await page.screenshot({ path: '../.runtime/change-review-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  await expect(section.locator('.diff-scroll')).toBeVisible();
  await page.screenshot({ path: '../.runtime/change-review-mobile.png', fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  const fixed = await (await page.request.get(`/api/scans/${fixedScan}/changes`)).json();
  const removed = fixed.review.files.find((f: any) => f.removedFingerprints.length > 0);
  expect(removed).toBeTruthy();
  await page.goto(`/scans/${fixedScan}`);
  await page.getByLabel('변경 파일', { exact: true }).selectOption(removed.changeId);
  await expect(section.locator('.change-risk').filter({ hasText: '미탐지' }).first()).toContainText('조치 완료 판정은 수행하지 않았습니다');
  const scans = await (await page.request.get('/api/scans')).json();
  const legacy = scans.find((s: any) => !s.hasChanges);
  expect(legacy).toBeTruthy();
  await page.goto(`/scans/${legacy.id}`);
  await expect(section).toContainText('이 검사는 코드 변경 근거를 수집하지 않았습니다');
  expect(errors).toEqual([]);
});
